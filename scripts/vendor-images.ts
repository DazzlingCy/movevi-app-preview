/** Run manually with `npx tsx scripts/vendor-images.ts` when adding default images.
 * Downloads existing artwork unchanged; normal builds never need external image hosts.
 */
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rename, stat, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { promisify } from 'node:util';
import { CITIES } from '../src/data/cities';
import { ROUTE_COVERS } from '../src/data/routeCovers';

const run = promisify(execFile);
const root = resolve(import.meta.dirname, '..');
const destination = resolve(root, 'public/images/journey');
await mkdir(destination, { recursive: true });
const app = await readFile(resolve(root, 'src/components/journey/JourneyApp.tsx'), 'utf8');
const cityBlock = app.match(/const JOURNEY_CITY_IMAGES[^=]*= ([\s\S]*?);/)?.[1];
if (!cityBlock) throw new Error('City image catalogue not found');
const cityUrls = [...cityBlock.matchAll(/https:\/\/[^']+/g)].map(match => match[0]);
const covers = Object.values(ROUTE_COVERS).flat();
// These legacy image URLs return 404. Use the same city's verified landmark photo.
const replacements = Object.fromEntries(['孟买', '曼谷', '莫斯科'].map(name => [
  CITIES.find(city => city.name === name)!.image, ROUTE_COVERS[name][0].src,
]));
const urls = [...new Set([
  ...covers.map(cover => cover.src), ...cityUrls, ...CITIES.map(city => city.image),
  ...[11, 12, 13].map(id => `https://i.pravatar.cc/100?img=${id}`),
])].filter(url => !replacements[url]);
const files = await readdir(destination);
const manifest: Record<string, string> = {};
const failures: string[] = [];
let completed = 0;
let nextIndex = 0;

function extension(bytes: Buffer) {
  if (bytes[0] === 0xff && bytes[1] === 0xd8) return 'jpg';
  if (bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) return 'png';
  if (bytes.toString('ascii', 0, 4) === 'RIFF' && bytes.toString('ascii', 8, 12) === 'WEBP') return 'webp';
  if (bytes.toString('ascii', 0, 3) === 'GIF') return 'gif';
  throw new Error('Response is not a supported raster image');
}

async function download(url: string) {
  const hash = createHash('sha256').update(url).digest('hex').slice(0, 20);
  const existing = files.find(file => file.startsWith(`${hash}.`) && !file.endsWith('.part'));
  if (existing) {
    extension(await readFile(resolve(destination, existing)));
    manifest[url] = `images/journey/${existing}`;
    return;
  }
  const temporary = resolve(destination, `${hash}.part`);
  // A few catalogue entries point at full-size originals. Fetch their normal
  // Wikimedia thumbnail to avoid multi-megabyte mobile downloads.
  const originalPrefix = 'https://upload.wikimedia.org/wikipedia/commons/';
  const originalPath = url.startsWith(originalPrefix) ? url.slice(originalPrefix.length) : '';
  const downloadUrl = originalPath && !originalPath.startsWith('thumb/')
    ? `https://thumb.wikimedia.org/wikipedia/commons/thumb/${originalPath}/960px-${originalPath.split('/').at(-1)}`
    : url;
  const { stdout } = await run(process.platform === 'win32' ? 'curl.exe' : 'curl', ['--fail', '--silent', '--show-error', '--location',
    '--retry', '1', '--retry-delay', '3', '--retry-max-time', '60', '--connect-timeout', '15', '--max-time', '45',
    '--output', temporary, '--write-out', '%{content_type}', downloadUrl], { windowsHide: true });
  if (!stdout.trim().startsWith('image/')) throw new Error(`Unexpected content type ${stdout}`);
  const bytes = await readFile(temporary);
  const name = `${hash}.${extension(bytes)}`;
  await rename(temporary, resolve(destination, name));
  manifest[url] = `images/journey/${name}`;
}

await Promise.all(Array.from({ length: 2 }, async () => {
  while (nextIndex < urls.length) {
    const url = urls[nextIndex++];
    try { await download(url); }
    catch (error) { failures.push(url); console.error(`FAILED ${url}: ${String(error)}`); }
    completed += 1;
    if (completed % 20 === 0 || completed === urls.length) console.log(`${completed}/${urls.length} images processed`);
  }
}));
if (failures.length) throw new Error(`${failures.length} image downloads failed. Re-run to retry; verified downloads are reused.`);
for (const [original, replacement] of Object.entries(replacements)) manifest[original] = manifest[replacement];

const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
await writeFile(resolve(root, 'src/data/localImageManifest.ts'),
  `// Generated by scripts/vendor-images.ts; original URLs remain as attribution/provenance.\nexport const LOCAL_IMAGE_MANIFEST: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`);
await writeFile(resolve(destination, 'attribution.json'), JSON.stringify({
  note: 'Images are unmodified copies. Licenses and original sources are retained below.',
  routeCovers: covers.map(cover => ({ ...cover, localPath: manifest[cover.src] })),
  otherImages: Object.entries(sorted).filter(([url]) => !covers.some(cover => cover.src === url)).map(([source, localPath]) => ({ source, replacementSource: replacements[source], localPath })),
}, null, 2) + '\n');
const totalBytes = (await Promise.all(Object.values(manifest).map(path => stat(resolve(root, 'public', path))))).reduce((sum, file) => sum + file.size, 0);
console.log(`Vendored ${urls.length} images (${(totalBytes / 1024 / 1024).toFixed(1)} MiB)`);
